#!/usr/bin/env python3
"""Summarise the raw council layers in data/raw/ as a Markdown report.

Run after fetch.py. Prints to stdout, or writes to a file with --out:

    python pipeline/summarise.py --out docs/data-summary.md
"""
from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"


def props(name: str) -> list[dict]:
    """Properties of a layer from the last fetch (layers not in the manifest are ignored)."""
    manifest = json.loads((RAW / "manifest.json").read_text(encoding="utf-8"))
    path = RAW / f"{name}.geojson"
    if name not in manifest["layers"]:
        return []
    if not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    return [f["properties"] for f in data["features"]]


def clean(value) -> str:
    """Council text fields carry stray spaces ('Loading Zone ') and blanks."""
    text = " ".join(str(value).split()) if value is not None else ""
    return text or "(blank)"


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def counter_table(counter: Counter, label: str, limit: int | None = None) -> str:
    rows = [[k, v] for k, v in counter.most_common(limit)]
    return table([label, "Count"], rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, help="write Markdown here instead of stdout")
    args = parser.parse_args()

    manifest = json.loads((RAW / "manifest.json").read_text(encoding="utf-8"))
    md: list[str] = [
        "# Council data summary",
        "",
        "Generated by `pipeline/summarise.py` from the last `fetch.py` run. Don't edit by hand.",
        "",
        f"- Fetched: {manifest['fetched_at']}",
        f"- Scope: {manifest['scope']} ({', '.join(s.title() for s in manifest['suburbs'])})",
        "",
        "## Layers",
        "",
        table(
            ["Layer", "Features", "Filter", "Council data last edited"],
            [[n, i["features"], i["filter"], i["data_last_edit"]] for n, i in manifest["layers"].items()],
        ),
    ]

    lines = props("lines")
    if lines:
        md += ["", "## Painted lines", ""]
        md += ["By suburb:", "", counter_table(Counter(clean(p["SUBURB"]) for p in lines), "Suburb"), ""]
        md += ["Lifecycle (only 'In Service' lines are still on the road):", ""]
        md += [counter_table(Counter(clean(p["ASSETLIFECYCLE"]) for p in lines), "Lifecycle"), ""]

        agg: dict[tuple, list] = defaultdict(lambda: [0, 0.0])
        for p in lines:
            if clean(p["ASSETLIFECYCLE"]) != "In Service":
                continue
            key = (clean(p["PARKINGRESTRICTIONTYPE"]), clean(p["PAVEMENTMARKINGSUBTYPE"]), clean(p["MARKINGCOLOUR"]))
            agg[key][0] += 1
            agg[key][1] += float(p.get("PAVEMENTLINELENGTH") or 0)
        rows = [[*k, n, f"{m:,.0f}"] for k, (n, m) in sorted(agg.items(), key=lambda kv: -kv[1][1])]
        md += ["In-service lines by type (sorted by total length):", ""]
        md += [table(["Restriction type", "Marking subtype", "Colour", "Segments", "Metres"], rows)]

    signs = props("signs")
    if signs:
        md += ["", "## Signs", ""]
        md += [counter_table(Counter(clean(p["SIGNCATEGORY"]) for p in signs), "Sign category"), ""]
        md += ["Top 30 restriction types:", ""]
        md += [counter_table(Counter(clean(p["PARKINGRESTRICTIONTYPE"]) for p in signs), "Restriction type", 30), ""]
        md += [counter_table(Counter(clean(p["SIGNDIRECTION"]) for p in signs), "Arrow direction")]

    clearways = props("clearways")
    if clearways:
        md += ["", "## Clearways", "", "Operating times as written by council (free text, needs parsing):", ""]
        md += [counter_table(Counter(clean(p["OPERATIONAL_TIME"]) for p in clearways), "Operating time")]

    text = "\n".join(md) + "\n"
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        print(f"Wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
